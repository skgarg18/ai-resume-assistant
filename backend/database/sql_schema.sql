-- ============================================================================
-- Resume AI Assistant - PostgreSQL Database Schema
-- ============================================================================
--
-- Purpose:
-- This file creates the complete PostgreSQL schema required for the
-- Resume AI Assistant application.
--
-- It includes:
--   • Required PostgreSQL extensions
--   • All application tables
--   • Primary & Foreign Keys
--   • Default values
--   • Indexes for faster queries
--
-- Note:
-- Embeddings are stored in ChromaDB, therefore this schema stores only the
-- metadata of each chunk (not the embedding vector itself).
--
-- Execution:
-- Run this file once on a fresh PostgreSQL database.
--
-- ============================================================================



-- ============================================================================
-- EXTENSIONS
-- ============================================================================

-- Generates random UUIDs using gen_random_uuid()
CREATE EXTENSION IF NOT EXISTS pgcrypto;



-- ============================================================================
-- USERS
-- ============================================================================
--
-- Stores authenticated users after Google OAuth login.
--
-- One user can have multiple screening sessions.
--
-- Relationship:
-- users (1) ------> (N) sessions
--
-- ============================================================================

CREATE TABLE IF NOT EXISTS users (

    -- Internal Primary Key
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Google OAuth Unique ID
    google_id TEXT UNIQUE NOT NULL,

    -- User Email
    email TEXT UNIQUE NOT NULL,

    -- User Display Name
    name TEXT,

    -- Google Profile Picture
    picture TEXT,

    -- Refresh Token for Google APIs
    refresh_token TEXT,

    -- Audit Fields
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);



-- ============================================================================
-- SESSIONS
-- ============================================================================
--
-- Represents one Resume Screening Session.
--
-- Every Job Description uploaded creates one session.
--
-- One user can have many sessions.
--
-- Relationship:
-- users (1) ------> (N) sessions
--
-- ============================================================================

CREATE TABLE IF NOT EXISTS sessions (

    -- Primary Key
    session_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    -- Owner of this session
    user_id BIGINT NOT NULL,

    -- User Friendly Session Name
    session_name TEXT,

    -- Complete Job Description
    job_description TEXT,

    -- Creation Timestamp
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_sessions_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
        ON DELETE CASCADE
);



-- ============================================================================
-- RESUMES
-- ============================================================================
--
-- Stores shortlisted resume information.
--
-- One session can contain multiple resumes.
--
-- Relationship:
-- sessions (1) ------> (N) resumes
--
-- ============================================================================

CREATE TABLE IF NOT EXISTS resumes (

    -- Primary Key
    resume_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    -- Parent Session
    session_id UUID NOT NULL,

    -- Candidate Details
    name TEXT,
    email TEXT,
    contact TEXT,

    -- Resume Match Score (0-100)
    score INTEGER,

    -- AI Generated Summary
    summary TEXT,

    -- Skills identified by AI
    matched_skills TEXT[],

    -- Missing skills identified by AI
    missing_skills TEXT[],

    -- Resume PDF stored on disk / cloud
    pdf_url TEXT,

    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_resumes_session
        FOREIGN KEY (session_id)
        REFERENCES sessions(session_id)
        ON DELETE CASCADE
);



-- ============================================================================
-- RESUME CHUNKS
-- ============================================================================
--
-- Stores chunk metadata.
--
-- Actual embeddings are stored inside ChromaDB.
--
-- PostgreSQL stores only:
--
-- • Which session the chunk belongs to
-- • Which resume it belongs to
-- • Candidate Name
-- • Chunk Text
-- • Chunk Order
--
-- Relationship:
--
-- sessions (1) ------> (N) resume_chunks
-- resumes  (1) ------> (N) resume_chunks
--
-- ============================================================================

CREATE TABLE IF NOT EXISTS resume_chunks (

    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    session_id UUID NOT NULL,

    resume_id UUID NOT NULL,

    candidate_name TEXT,

    chunk_index INTEGER,

    chunk_text TEXT,

    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_chunks_session
        FOREIGN KEY (session_id)
        REFERENCES sessions(session_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_chunks_resume
        FOREIGN KEY (resume_id)
        REFERENCES resumes(resume_id)
        ON DELETE CASCADE
);



-- ============================================================================
-- EMAIL DRAFTS
-- ============================================================================
--
-- Stores AI generated interview email drafts.
--
-- Drafts can later be:
--
-- • Edited
-- • Regenerated
-- • Sent
--
-- Relationship:
--
-- sessions (1) ------> (N) email_drafts
--
-- ============================================================================

CREATE TABLE IF NOT EXISTS email_drafts (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    session_id UUID NOT NULL,

    candidate_name TEXT,

    recipient_email TEXT,

    subject TEXT,

    body TEXT,

    status TEXT,

    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

    sent_at TIMESTAMPTZ,

    original_prompt TEXT,

    regeneration_count INTEGER DEFAULT 0,

    meeting_metadata JSONB,

    CONSTRAINT fk_email_session
        FOREIGN KEY (session_id)
        REFERENCES sessions(session_id)
        ON DELETE CASCADE
);



-- ============================================================================
-- CHAT HISTORY
-- ============================================================================
--
-- Stores complete recruiter ↔ AI conversation.
--
-- This includes:
--
-- • User Questions
-- • AI Responses
-- • Generated Emails
-- • Email Metadata
--
-- Relationship:
--
-- sessions (1) ------> (N) chat_history
--
-- ============================================================================

CREATE TABLE IF NOT EXISTS chat_history (

    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    session_id UUID NOT NULL,

    user_message TEXT,

    assistant_message TEXT,

    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

    message_type TEXT,

    email_id TEXT,

    email_subject TEXT,

    email_body TEXT,

    draft_id BIGINT,

    email_meeting_metadata JSONB,

    CONSTRAINT fk_chat_session
        FOREIGN KEY (session_id)
        REFERENCES sessions(session_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_chat_draft
        FOREIGN KEY (draft_id)
        REFERENCES email_drafts(id)
        ON DELETE SET NULL
);



-- ============================================================================
-- INDEXES
-- ============================================================================
--
-- These indexes improve query performance.
--
-- ============================================================================

-- Lookup all sessions of a user
CREATE INDEX IF NOT EXISTS idx_sessions_user
ON sessions(user_id);

-- Fetch resumes of a session
CREATE INDEX IF NOT EXISTS idx_resumes_session
ON resumes(session_id);

-- Fetch chunks by session
CREATE INDEX IF NOT EXISTS idx_resume_chunks_session
ON resume_chunks(session_id);

-- Fetch chunks of a resume
CREATE INDEX IF NOT EXISTS idx_resume_chunks_resume
ON resume_chunks(resume_id);

-- Fetch drafts of a session
CREATE INDEX IF NOT EXISTS idx_email_session
ON email_drafts(session_id);

-- Fetch chat history of a session
CREATE INDEX IF NOT EXISTS idx_chat_session
ON chat_history(session_id);

-- Google Login Lookup
CREATE INDEX IF NOT EXISTS idx_users_google_id
ON users(google_id);

-- Email Lookup
CREATE INDEX IF NOT EXISTS idx_users_email
ON users(email);



